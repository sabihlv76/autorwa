function seller(id: string) {
  const found = getSellerById(id);
  if (!found) throw new Error(`Unknown mock seller id: ${id}`);
  return found;
}

function daysAgo(days: number): string {
  const date = new Date();
  date.setDate(date.getDate() - days);
  return date.toISOString();
}

